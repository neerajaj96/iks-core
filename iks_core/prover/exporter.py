"""Lean exporter: inference records -> theorems against lean/IksNN.lean kernel.

Maps hetvabhasa labels to detector inputs (inverse of detect_hetvabhasa):
  none          -> full trairupya, no defeaters
  Savyabhicara  -> vipakse present
  Viruddha      -> contradicts_sadhya
  Satpratipaksa -> counter_reason (+sapakse)
  Asiddha       -> pakse absent
  Badhita       -> defeated
"""
from __future__ import annotations

LABEL_FLAGS = {
    "none": dict(pakse=True, sapakse=True, vipakse_present=False,
                 contradicts_sadhya=False, defeated=False, counter_reason=False),
    "Savyabhicara": dict(pakse=True, sapakse=True, vipakse_present=True,
                         contradicts_sadhya=False, defeated=False, counter_reason=False),
    "Viruddha": dict(pakse=True, sapakse=True, vipakse_present=False,
                     contradicts_sadhya=True, defeated=False, counter_reason=False),
    "Satpratipaksa": dict(pakse=True, sapakse=True, vipakse_present=False,
                          contradicts_sadhya=False, defeated=False, counter_reason=True),
    "Asiddha": dict(pakse=False, sapakse=False, vipakse_present=False,
                    contradicts_sadhya=False, defeated=False, counter_reason=False),
    "Badhita": dict(pakse=True, sapakse=True, vipakse_present=False,
                    contradicts_sadhya=False, defeated=True, counter_reason=False),
}

LEAN_OPT = {True: "true", False: "false"}
LEAN_LABEL = {"none": "none", "Savyabhicara": ".savyabhicara", "Viruddha": ".viruddha",
              "Satpratipaksa": ".satpratipaksa", "Asiddha": ".asiddha", "Badhita": ".badhita"}


def ident(s: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in s)[:40].strip("_") or "inf"


def export_inference(rec: dict) -> str:
    name = ident(rec["id"])
    fl = LABEL_FLAGS[rec.get("hetvabhasa", "none")]
    args = " ".join(LEAN_OPT[fl[k]] for k in
                    ("pakse", "sapakse", "vipakse_present", "contradicts_sadhya",
                     "defeated", "counter_reason"))
    want = LEAN_LABEL[rec.get("hetvabhasa", "none")]
    want_lean = "none" if want == "none" else f"(some {want})"
    lines = [
        f"-- auto-generated from {rec['id']} ({rec.get('form', '')}); do not hand-edit",
        f"def {name}_trairupya : Trairupya := ⟨{LEAN_OPT[fl['pakse']]}, "
        f"{LEAN_OPT[fl['sapakse']]}, {str(not fl['vipakse_present']).lower()}⟩",
        f"theorem {name}_holds : trairupyaHolds {name}_trairupya = "
        f"{'true' if (fl['pakse'] and fl['sapakse'] and not fl['vipakse_present']) else 'false'} := rfl",
        f"theorem {name}_detect : detectHetvabhasa {args} = {want_lean} := rfl",
    ]
    return "\n".join(lines) + "\n"


def export_all(records: list[dict]) -> str:
    head = ("-- Generated by iks_core.prover.exporter — machine-checked companion\n"
            "-- to data/inferences.json. Build with: lake env lean lean/generated/All.lean\n"
            "import IksNN\n\n")
    return head + "\n".join(export_inference(r) for r in records)
